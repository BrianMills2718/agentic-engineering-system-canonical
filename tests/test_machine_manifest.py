@pytest.mark.req("machine-manifest/missing-or-untracked-target-is-reported")
def test_missing_or_untracked_targets_and_drift_are_reported(machine):
    recorded = m.build(machine, is_enabled=enabled)
    found = m.findings(recorded, recorded)
    assert found["bad-target"] == ["gone.service (target missing)", "untracked.service (target not tracked by git)"]
