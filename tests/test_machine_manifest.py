SECRET = "sk-test-not-a-real-value-123"
GIT = ["git", "-c", "user.name=t", "-c", "user.email=t@t", "-c", "commit.gpgsign=false", "-c", "core.hooksPath=/dev/null"]


def git(repo, *args):
    subprocess.run([*GIT, "-C", str(repo), *args], check=True, capture_output=True)


@pytest.fixture
def machine(tmp_path):
    """A unit folder holding one example of each kind of source."""
    repo, units = tmp_path / "repo", tmp_path / "units"
    (repo / "systemd").mkdir(parents=True)
    units.mkdir()
    git(repo, "init", "-q")
    git(repo, "remote", "add", "origin", "git@github.com:someone/jobs.git")
    (repo / "run.sh").write_text("#!/bin/sh\n")
    (repo / "systemd/tracked.service").write_text(f"[Service]\nExecStart=/bin/bash {repo}/run.sh --flag {SECRET}\n")
    (repo / "systemd/tracked.timer").write_text("[Timer]\nOnCalendar=daily\nPersistent=true\n")
    git(repo, "add", ".")
    git(repo, "commit", "-qm", "jobs")
    (repo / "systemd/untracked.service").write_text("[Service]\nExecStart=/usr/bin/true\n")
    (units / "tracked.service").symlink_to(repo / "systemd/tracked.service")
    (units / "tracked.timer").symlink_to(repo / "systemd/tracked.timer")
    (units / "untracked.service").symlink_to(repo / "systemd/untracked.service")
    (units / "gone.service").symlink_to(repo / "systemd/never-existed.service")
    (units / "handmade.service").write_text(f"[Service]\nEnvironment=TOKEN={SECRET}\nEnvironmentFile=%h/.secrets/{SECRET}.env\n"
                                            "ExecStart=%h/bin/handmade\n")
    (units / "handmade.timer").write_text("[Timer]\nOnUnitInactiveSec=1h\n")
    (units / "listed.service").write_text("# Generated by aes scripts/timers.py from the job list; edit the list, not this file.\n"
                                          "[Service]\nExecStart=/usr/bin/true\n")
    (units / "listed.timer").write_text("# Generated by aes scripts/timers.py from the job list; edit the list, not this file.\n"
                                        "[Timer]\nOnCalendar=hourly\n")
    (units / "tracked.service.d").mkdir()
    (units / "tracked.service.d/override.conf").write_text(f"[Service]\nEnvironment=\"KEY={SECRET}\"\n")
    (units / "tracked.timer.d").mkdir()
    (units / "tracked.timer.d/later.conf").write_text("[Timer]\nOnCalendar=\nOnCalendar=*-*-* 04:00:00\n")
    return units


def enabled(unit):
    return "enabled"


def unit(manifest, name):
    return next(u for u in manifest["units"] if u["name"] == name)


@pytest.mark.req("machine-manifest/every-unit-has-a-source")
def test_every_unit_and_dropin_has_a_source(machine):
    manifest = m.build(machine, is_enabled=enabled)
    files = m.files_of(manifest)
    assert len(files) == 10 and all(src.get("kind") for src in files.values())
    tracked = unit(manifest, "tracked")
    assert tracked["service"]["source"] == {"kind": "git", "repo": "someone/jobs", "checkout": tracked["service"]["source"]["checkout"],
                                            "path": "systemd/tracked.service", "tracked": True, "committed": True}
    assert tracked["timer"]["schedule"] == {"OnCalendar": ["*-*-* 04:00:00"], "Persistent": ["true"]}
    assert tracked["service"]["program"] == "/bin/bash" and tracked["service"]["script_repo"] == "someone/jobs"
    assert tracked["service"]["script"].endswith("/repo/run.sh")
    assert [d["source"]["kind"] for d in tracked["dropins"]] == ["local-only", "local-only"]
    assert unit(manifest, "listed")["timer"]["source"] == {"kind": "job-list", "job": "listed"}
    assert unit(manifest, "handmade")["service"]["source"] == {"kind": "local-only"}
    assert unit(manifest, "handmade")["enabled"] == "enabled"


@pytest.mark.req("machine-manifest/local-only-units-are-reported")
def test_local_only_files_are_reported_and_fail_the_check(machine, tmp_path, capsys):
    found = m.findings(m.build(machine, is_enabled=enabled), None)
    assert found["local-only"] == ["handmade.service", "handmade.timer", "tracked.service.d/override.conf",
                                   "tracked.timer.d/later.conf"]
    path = tmp_path / "manifest.yaml"
    assert m.main(["build", "--unit-dir", str(machine), "--out", str(path)], is_enabled=enabled) == 0
    assert m.main(["check", "--unit-dir", str(machine), "--manifest", str(path)], is_enabled=enabled) == 1
    out = capsys.readouterr().out
    assert "(a) local-only files, lost on a clean machine: 4" in out and "  handmade.timer" in out


@pytest.mark.req("machine-manifest/missing-or-untracked-target-is-reported")
def test_missing_or_untracked_targets_and_drift_are_reported(machine):
    recorded = m.build(machine, is_enabled=enabled)
    found = m.findings(recorded, recorded)
    assert found["bad-target"] == ["gone.service (target missing)", "untracked.service (target not tracked by git)"]
    assert found["gone-from-disk"] == [] and found["not-in-manifest"] == []
    (machine / "handmade.timer").unlink()
    (machine / "new.timer").write_text("[Timer]\nOnCalendar=daily\n")
    drift = m.findings(m.build(machine, is_enabled=enabled), recorded)
    assert drift["gone-from-disk"] == ["handmade.timer"] and drift["not-in-manifest"] == ["new.timer"]


@pytest.mark.req("machine-manifest/missing-or-untracked-target-is-reported")
def test_clean_machine_passes_the_check(tmp_path):
    units = tmp_path / "units"
    units.mkdir()
    (units / "listed.service").write_text("# Generated by aes scripts/timers.py\n[Service]\nExecStart=/usr/bin/true\n")
    manifest = m.build(units, is_enabled=enabled)
    assert not any(m.findings(manifest, manifest).values())


@pytest.mark.req("machine-manifest/output-is-stable")
def test_output_is_sorted_and_identical_across_builds(machine):
    first = m.dump(m.build(machine, is_enabled=enabled))
    assert first == m.dump(m.build(machine, is_enabled=enabled))
    names = [u["name"] for u in yaml.safe_load(first)["units"]]
    assert names == sorted(names)


@pytest.mark.req("machine-manifest/no-environment-values-are-written")
def test_no_environment_value_or_argument_is_written(machine):
    text = m.dump(m.build(machine, is_enabled=enabled))
    assert SECRET not in text and "TOKEN" not in text and "--flag" not in text and ".secrets" not in text
    handmade = unit(yaml.safe_load(text), "handmade")["service"]
    assert handmade["environment_settings"] == 1 and handmade["environment_files"] == 1
    assert unit(yaml.safe_load(text), "tracked")["service"]["environment_settings"] == 1


@pytest.mark.req("machine-manifest/no-environment-values-are-written")
def test_inline_commands_keep_only_the_program_and_modules_are_named():
    assert m.command_parts(f"/bin/bash -c 'curl -H {SECRET} x'") == ("/bin/bash", None, None)
    assert m.command_parts("/usr/bin/python3 -m pkg.job --token abc") == ("/usr/bin/python3", None, "pkg.job")
    assert m.command_parts("/usr/bin/nice -n 10 /usr/bin/python3 /opt/x/run.py") == ("/usr/bin/nice", "/opt/x/run.py", None)
