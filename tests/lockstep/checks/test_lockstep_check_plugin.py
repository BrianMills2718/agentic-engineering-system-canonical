"""Tests for the pytest plugin, the top-level wiring and the modes of `lockstep check project`."""

from importlib.metadata import entry_points
import subprocess
import sys

import pytest

from lockstep.checks import plugin
from lockstep_checks_support import write, repo  # noqa: F401  (fixture)

IMPL = '''
    """Core module."""


    def run():
        """Run the thing.

        Implements: core/do-the-thing
        """
'''


class _Config:
    """Records the lines the plugin registers."""

    def __init__(self) -> None:
        self.lines: list[tuple[str, str]] = []

    def addinivalue_line(self, name: str, line: str) -> None:
        """Record one registered ini line."""
        self.lines.append((name, line))


@pytest.mark.req("lockstep-projection/the-plugin-registers-the-req-marker")
def test_plugin_registers_the_req_marker():
    config = _Config()
    plugin.pytest_configure(config)
    assert [n for n, _ in config.lines] == ["markers"]
    assert config.lines[0][1].startswith("req(id, existing=False)")


@pytest.mark.req("lockstep-projection/the-plugin-registers-the-req-marker")
def test_plugin_is_a_pytest11_entry_point():
    found = {e.name: e.value for e in entry_points(group="pytest11")}
    assert found["lockstep"] == "lockstep.checks.plugin"


@pytest.mark.req("lockstep-projection/the-plugin-registers-the-req-marker")
def test_plugin_and_the_ini_marker_can_both_register(tmp_path):
    write(tmp_path, "test_x.py", 'import pytest\n\n@pytest.mark.req("a/b")\ndef test_x():\n    pass\n')
    write(tmp_path, "pytest.ini", "[pytest]\nmarkers = req(c): declared in the ini too\n")
    done = subprocess.run([sys.executable, "-m", "pytest", "--strict-markers", "-q", "-p", "no:cacheprovider"],
                          cwd=tmp_path, capture_output=True, text=True)
    assert done.returncode == 0 and "1 passed" in done.stdout, done.stdout + done.stderr


@pytest.mark.req("lockstep-projection/the-commands-are-top-level-and-check-modes-apply")
def test_top_level_status_and_show_and_check_project(repo, monkeypatch, capsys):
    from lockstep.check import cli

    write(repo, "src/pkg/mod.py", IMPL)
    for argv, needle in [
        (["status", "--repo", str(repo)], "RESULT status requirements=1"),
        (["show", "--repo", str(repo), "src/pkg/mod.py"], "RESULT show requirements=1 exit=0"),
        (["check", "project", "--repo", str(repo), "--check"], "stale         src/pkg/mod.py"),
    ]:
        monkeypatch.setattr(sys, "argv", ["lockstep", *argv])
        status = cli()
        assert needle in capsys.readouterr().out
        assert status == (1 if argv[0] == "check" else 0)


@pytest.mark.req("lockstep-projection/the-commands-are-top-level-and-check-modes-apply")
@pytest.mark.parametrize("mode,exit_,words", [("warn", 0, "warning: project failed"), ("off", 0, "project: skipped (off)")])
def test_project_mode_from_lockstep_yaml(repo, mode, exit_, words, capsys):
    from lockstep.checks.cli import run

    write(repo, "src/pkg/mod.py", IMPL)
    write(repo, "lockstep.yaml", f"checks:\n  project: {mode}\n")
    before = (repo / "src/pkg/mod.py").read_text()
    assert run(["project", "--repo", str(repo), "--check"]) == exit_
    assert words in capsys.readouterr().out
    assert (repo / "src/pkg/mod.py").read_text() == before


@pytest.mark.req("lockstep-projection/the-commands-are-top-level-and-check-modes-apply")
def test_source_folders_come_from_either_pyproject_table(repo):
    from lockstep.checks.project import project

    for table in ("lockstep", "code2check"):
        write(repo, "pyproject.toml", f"[tool.{table}]\nsource = ['lib']\n")
        write(repo, "lib/m.py", '"""M.\n\nImplements: core/do-the-thing\n"""\n')
        assert project(repo, check=True) == ["lib/m.py"]
        (repo / "lib/m.py").unlink()


@pytest.mark.req("lockstep-projection/a-plan-block-written-by-code2check-is-replaced-not-duplicated")
def test_old_code2check_block_is_replaced(repo):
    from lockstep.checks.project import project

    write(repo, "docs/plans/0001-x.md", "Closes: core/do-the-thing\n\n<!-- code2check status: generated by `code2check project`; do not edit -->\n\n- old\n\n<!-- /code2check status -->\n\n## Goal\n")
    assert "docs/plans/0001-x.md" in project(repo)
    text = (repo / "docs/plans/0001-x.md").read_text()
    assert "code2check" not in text and text.count("<!-- /lockstep status -->") == 1 and "- old" not in text
