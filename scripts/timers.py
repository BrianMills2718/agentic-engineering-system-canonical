#!/usr/bin/env python3
"""Render, check or install systemd user timers from one list of jobs (retirement plan step 6, Decision 21).

The machinery is generic. A person's own list (`timers.yaml`: each job with its command, schedule and the reason it
exists) lives in their private configuration repository; another person supplies a different list.

    timers.py render  LIST [--out DIR]    write the unit files into DIR (default ./units) and change nothing else
    timers.py check   LIST [--dir DIR]    compare the rendered files with the installed ones; exit 1 on any difference
    timers.py install LIST [--dir DIR]    back up differing installed files, write the new ones, run daemon-reload

Implements: timer-config/jobs-become-units
"""
from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path

import yaml

NAME = re.compile(r"^[a-z0-9][a-z0-9@_.-]*$")
SCHEDULE_KEYS = {"on_calendar", "on_boot_sec", "on_unit_active_sec", "persistent", "randomized_delay"}
JOB_KEYS = {"name", "description", "why", "documentation", "after", "working_directory", "environment", "exec_condition",
            "exec_pre", "exec_start", "success_exit_status", "timeout", "nice", "append_output_to", "schedule"}


def load(path: Path) -> list[dict]:
    """The jobs in the list; fails loudly on a missing reason, a bad name, an unknown key or a repeated name."""
    data = yaml.safe_load(path.read_text())
    jobs = data.get("timers") if isinstance(data, dict) else None
    if not isinstance(jobs, list) or not jobs:
        raise ValueError(f"{path}: expected a non-empty `timers:` list")
    seen: set[str] = set()
    for job in jobs:
        name = job.get("name", "")
        if not NAME.match(name):
            raise ValueError(f"{path}: bad job name {name!r}")
        if name in seen:
            raise ValueError(f"{path}: job {name} listed twice")
        seen.add(name)
        for required in ("description", "why", "exec_start", "schedule"):
            if not job.get(required):
                raise ValueError(f"{path}: job {name} has no `{required}`")
        extra = set(job) - JOB_KEYS
        if extra:
            raise ValueError(f"{path}: job {name} has unknown keys {sorted(extra)}")
        extra = set(job["schedule"]) - SCHEDULE_KEYS
        if extra:
            raise ValueError(f"{path}: job {name} schedule has unknown keys {sorted(extra)}")
        for value in _strings(job):
            if "\n" in value or "\0" in value:
                raise ValueError(f"{path}: job {name} has a newline or NUL in a value")
    return jobs


def _strings(job: dict):
    for value in job.values():
        if isinstance(value, str):
            yield value
        elif isinstance(value, list):
            yield from (v for v in value if isinstance(v, str))
        elif isinstance(value, dict):
            for k, v in value.items():
                yield str(k)
                yield str(v)


def render_service(job: dict) -> str:
    unit = [f"Description={job['description']}"]
    if job.get("documentation"):
        unit.append(f"Documentation={job['documentation']}")
    if job.get("after"):
        unit.append(f"After={job['after']}")
    service = ["Type=oneshot"]
    if job.get("working_directory"):
        service.append(f"WorkingDirectory={job['working_directory']}")
    for key, value in (job.get("environment") or {}).items():
        service.append(f'Environment="{key}={value}"')
    for cond in job.get("exec_condition") or []:
        service.append(f"ExecCondition={cond}")
    for pre in job.get("exec_pre") or []:
        service.append(f"ExecStartPre={pre}")
    service.append(f"ExecStart={job['exec_start']}")
    if job.get("success_exit_status") is not None:
        service.append(f"SuccessExitStatus={job['success_exit_status']}")
    if job.get("timeout"):
        service.append(f"TimeoutStartSec={job['timeout']}")
    if job.get("nice") is not None:
        service.append(f"Nice={job['nice']}")
    if job.get("append_output_to"):
        service.append(f"StandardOutput=append:{job['append_output_to']}")
        service.append(f"StandardError=append:{job['append_output_to']}")
    text = "# Generated by aes scripts/timers.py from the job list; edit the list, not this file.\n"
    text += f"# Why: {job['why']}\n"
    text += "[Unit]\n" + "\n".join(unit) + "\n\n[Service]\n" + "\n".join(service) + "\n"
    return text


def render_timer(job: dict) -> str:
    s = job["schedule"]
    lines = []
    for key, directive in (("on_calendar", "OnCalendar"), ("on_boot_sec", "OnBootSec"), ("on_unit_active_sec", "OnUnitActiveSec")):
        if s.get(key):
            lines.append(f"{directive}={s[key]}")
    if s.get("persistent") is not None:
        lines.append(f"Persistent={'true' if s['persistent'] else 'false'}")
    if s.get("randomized_delay"):
        lines.append(f"RandomizedDelaySec={s['randomized_delay']}")
    if not any(s.get(k) for k in ("on_calendar", "on_boot_sec", "on_unit_active_sec")):
        raise ValueError(f"job {job['name']}: schedule names no trigger")
    return (f"# Generated by aes scripts/timers.py from the job list; edit the list, not this file.\n"
            f"[Unit]\nDescription=Timer for {job['name']}\n\n[Timer]\n" + "\n".join(lines) + "\n\n[Install]\nWantedBy=timers.target\n")


def render(jobs: list[dict]) -> dict[str, str]:
    files: dict[str, str] = {}
    for job in jobs:
        files[f"{job['name']}.service"] = render_service(job)
        files[f"{job['name']}.timer"] = render_timer(job)
    return files


def differences(files: dict[str, str], directory: Path) -> list[str]:
    changed = []
    for name, text in sorted(files.items()):
        target = directory / name
        if not target.exists() or target.read_text() != text:
            changed.append(name)
    return changed


def install(files: dict[str, str], directory: Path, backup_root: Path, run=subprocess.run) -> list[str]:
    """Back up each differing installed file (never delete), write the new ones, reload systemd."""
    changed = differences(files, directory)
    if changed:
        backup = backup_root / datetime.now().strftime("%Y%m%dT%H%M%S")
        backup.mkdir(parents=True, exist_ok=True)
        directory.mkdir(parents=True, exist_ok=True)
        for name in changed:
            if (directory / name).exists():
                shutil.copy2(directory / name, backup / name)
            (directory / name).write_text(files[name])
        done = run(["systemctl", "--user", "daemon-reload"], check=False)
        if done.returncode != 0:
            raise RuntimeError("systemctl --user daemon-reload failed")
    return changed


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["render", "check", "install"])
    ap.add_argument("list", type=Path)
    ap.add_argument("--out", type=Path, default=Path("units"))
    ap.add_argument("--dir", type=Path, default=Path.home() / ".config/systemd/user")
    ap.add_argument("--backup", type=Path, default=Path.home() / "archive/systemd-units-replaced")
    a = ap.parse_args(argv)
    files = render(load(a.list))
    if a.command == "render":
        a.out.mkdir(parents=True, exist_ok=True)
        for name, text in files.items():
            (a.out / name).write_text(text)
        print(f"timers: wrote {len(files)} files to {a.out}")
        return 0
    if a.command == "check":
        changed = differences(files, a.dir)
        print(f"timers: {len(files)} files rendered, {len(changed)} differ from {a.dir}" + (": " + ", ".join(changed) if changed else ""))
        return 1 if changed else 0
    changed = install(files, a.dir, a.backup)
    print(f"timers: installed {len(changed)} changed files into {a.dir}" + (": " + ", ".join(changed) if changed else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
