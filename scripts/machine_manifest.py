#!/usr/bin/env python3
"""Write and check a manifest of the systemd user units on this machine (AES consolidation plan, item 6).

A clean machine is rebuilt from git. A unit file that exists only on this disk would be lost, so the manifest
records, for every unit, where its file comes from: a git repository (the file is a symlink into it), the AES job
list (`scripts/timers.py` generated it), or nowhere (`local-only`).

    machine_manifest.py build [--unit-dir D] [--out FILE]        write the manifest (stdout without --out)
    machine_manifest.py check [--unit-dir D] [--manifest FILE] [--units-repo R]
                                                                 rebuild in memory, list what would be lost; exit 1 if any
    machine_manifest.py check-units [--unit-dir D] [--units-repo R]     compare the disk with the repository copies; exit 1 on a difference
    machine_manifest.py install-units [--apply] [--daemon-reload]       copy repository copies that are missing or differ (dry run unless --apply)

`build` and `check` are read-only: they read unit files, runs `git` read commands and `systemctl --user is-enabled`, and changes nothing.
It never writes an Environment= value or an EnvironmentFile's path or contents, only how many there are.

Implements: machine-manifest/every-unit-has-a-source
Implements: machine-manifest/local-only-units-are-reported
Implements: machine-manifest/missing-or-untracked-target-is-reported
Implements: machine-manifest/output-is-stable
Implements: machine-manifest/no-environment-values-are-written
Implements: machine-manifest/repository-copies-can-be-compared
Implements: machine-manifest/install-never-deletes-or-writes-through-links
"""
from __future__ import annotations

import argparse
import datetime
import os
import re
import shlex
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Callable

import yaml

UNIT_KINDS = ("timer", "service", "path", "socket", "slice")
GENERATED = "# Generated by aes scripts/timers.py"
SCHEDULE_KEYS = ("OnCalendar", "OnBootSec", "OnStartupSec", "OnActiveSec", "OnUnitActiveSec", "OnUnitInactiveSec",
                 "Persistent", "RandomizedDelaySec", "AccuracySec", "Unit")
# Programs that run the real script given as a later argument.
RUNNERS = {"bash", "sh", "zsh", "python", "python3", "uv", "uvx", "env", "node", "nice", "ionice", "flock", "timeout",
           "systemd-inhibit", "systemd-cat", "batch", "nohup", "perl", "ruby", "deno", "bun", "npx", "exec"}
HOME = str(Path.home())


def _git(directory: Path, *args: str) -> str | None:
    done = subprocess.run(["git", "-C", str(directory), *args], capture_output=True, text=True, check=False)
    return done.stdout.strip() if done.returncode == 0 else None


def _origin(url: str | None) -> str | None:
    """`owner/name` from an origin URL, or None."""
    if not url:
        return None
    m = re.search(r"[:/]([^/:]+/[^/]+?)(?:\.git)?/?$", url)
    return m.group(1) if m else url


class Git:
    """Read-only git lookups, cached per folder."""

    def __init__(self) -> None:
        self._top: dict[Path, str | None] = {}
        self._remote: dict[str, str | None] = {}

    def toplevel(self, directory: Path) -> str | None:
        if directory not in self._top:
            self._top[directory] = _git(directory, "rev-parse", "--show-toplevel") if directory.is_dir() else None
        return self._top[directory]

    def remote(self, top: str) -> str | None:
        if top not in self._remote:
            self._remote[top] = _origin(_git(Path(top), "remote", "get-url", "origin"))
        return self._remote[top]

    def file_source(self, target: Path) -> dict:
        """Where a resolved file lives in git: repository, path, tracked, committed."""
        top = self.toplevel(target.parent)
        if top is None:
            return {"kind": "symlink-outside-git", "target": _short(str(target))}
        rel = os.path.relpath(target, top)
        tracked = _git(Path(top), "ls-files", "--error-unmatch", "--", rel) is not None
        status = _git(Path(top), "status", "--porcelain", "--", rel)
        return {"kind": "git", "repo": self.remote(top) or "no-remote", "checkout": _short(top), "path": rel,
                "tracked": tracked, "committed": tracked and status == ""}

    def repo_of(self, path: Path) -> str:
        """`owner/name`, `no-remote` or `not-in-git` for any path (used for a job's script), after following links."""
        if path.exists():
            path = path.resolve()
        parent = path.parent
        while not parent.exists() and parent != parent.parent:
            parent = parent.parent
        top = self.toplevel(parent)
        if top is None:
            return "not-in-git"
        return self.remote(top) or "no-remote"


def _short(path: str) -> str:
    return "~" + path[len(HOME):] if path == HOME or path.startswith(HOME + "/") else path


def _expand(token: str) -> str:
    token = token.replace("%h", HOME).replace("${HOME}", HOME).replace("$HOME", HOME)
    return HOME + token[1:] if token.startswith("~/") else token


def source_of(path: Path, git: Git) -> dict:
    """The source of one unit or drop-in file. Implements: machine-manifest/every-unit-has-a-source"""
    linked = path.is_symlink() or path.parent.is_symlink()
    if linked:
        target = path.resolve()
        if not target.exists():
            return {"kind": "symlink-missing-target", "target": _short(str(target))}
        return git.file_source(target)
    try:
        first = path.read_text(errors="replace").split("\n", 1)[0]
    except OSError:
        first = ""
    if first.startswith(GENERATED):
        return {"kind": "job-list", "job": path.name.rsplit(".", 1)[0]}
    return {"kind": "local-only"}


def parse(text: str) -> list[tuple[str, str, str]]:
    """(section, key, value) for each directive, joining backslash continuations."""
    out, section, pending = [], "", ""
    for raw in text.splitlines():
        line = pending + raw.strip() if pending else raw.strip()
        if line.endswith("\\"):
            pending = line[:-1] + " "
            continue
        pending = ""
        if not line or line[0] in "#;":
            continue
        if line.startswith("[") and line.endswith("]"):
            section = line[1:-1]
        elif "=" in line:
            key, value = line.split("=", 1)
            out.append((section, key.strip(), value.strip()))
    return out


SCRIPT_SUFFIXES = (".py", ".sh", ".bash", ".js", ".mjs", ".ts", ".pl", ".rb")


def _is_runner(token: str) -> bool:
    name = Path(token).name
    return name in RUNNERS or name.startswith("python")


def command_parts(exec_start: str, workdir: str | None = None) -> tuple[str, str | None, str | None]:
    """The program, the script file it runs and a `-m` module; never other arguments (they may hold secrets).

    A `bash -c '...'` command has no script file, so only its program is recorded.
    """
    try:
        tokens = shlex.split(exec_start)
    except ValueError:
        tokens = exec_start.split()
    if not tokens:
        return "", None, None
    program = _expand(tokens[0].lstrip("-@+!:"))
    if not _is_runner(program):
        return _short(program), (_short(program) if "/" in program else None), None
    previous = ""
    for raw in tokens[1:]:
        token = _expand(raw)
        if previous == "-m":
            return _short(program), None, token
        previous = token
        if token == "-c":
            break
        if token.startswith("-") or "=" in token or any(c.isspace() for c in token) or _is_runner(token):
            continue
        path = Path(token) if token.startswith("/") or not workdir else Path(_expand(workdir)) / token
        if path.suffix in SCRIPT_SUFFIXES or (path.is_file() and os.access(path, os.X_OK)):
            return _short(program), _short(str(path)), None
    return _short(program), None, None


def describe(family: dict[str, Path], dropins: list[Path], git: Git, unit_dir: Path) -> dict:
    entry: dict = {}
    for kind in UNIT_KINDS:
        if kind in family:
            entry[kind] = {"file": family[kind].name, "source": source_of(family[kind], git)}
    # Implements: machine-manifest/no-environment-values-are-written (only counts of Environment= lines are kept)
    texts = {kind: parse(p.read_text(errors="replace")) for kind, p in family.items() if p.exists()}
    drop_texts = [(d, parse(d.read_text(errors="replace")) if d.exists() else []) for d in dropins]
    if "timer" in entry:
        schedule: dict[str, list[str]] = {}
        groups = [texts.get("timer", [])] + [t for d, t in drop_texts if d.parent.name.endswith(".timer.d")]
        for directives in groups:
            for section, key, value in directives:
                if section == "Timer" and key in SCHEDULE_KEYS:
                    if value == "":
                        schedule.pop(key, None)
                    else:
                        schedule.setdefault(key, []).append(value)
        entry["timer"]["schedule"] = schedule
    service_groups = [texts.get("service", [])] + [t for d, t in drop_texts if not d.parent.name.endswith(".timer.d")]
    starts: list[str] = []
    workdir: str | None = None
    env = env_files = 0
    for directives in service_groups:
        for section, key, value in directives:
            if section != "Service":
                continue
            if key == "WorkingDirectory":
                workdir = value.lstrip("-")
            elif key == "ExecStart":
                starts = [] if value == "" else starts + [value]
            elif key == "Environment":
                env += 1
            elif key == "EnvironmentFile":
                env_files += 1
    if "service" in entry or starts:
        target = entry.setdefault("service", {"file": None})
        if starts:
            program, script, module = command_parts(starts[0], workdir)
            target["program"] = program
            target["script"] = script
            if module:
                target["module"] = module
            if script:
                target["script_repo"] = git.repo_of(Path(_expand(script)))
        target["environment_settings"] = env
        target["environment_files"] = env_files
    if dropins:
        entry["dropins"] = [{"file": d.relative_to(unit_dir).as_posix(), "source": source_of(d, git)} for d in dropins]
    return entry


def scan(unit_dir: Path) -> tuple[dict[str, dict[str, Path]], dict[str, list[Path]]]:
    """Unit files by family name and kind, and drop-in files by family name."""
    families: dict[str, dict[str, Path]] = {}
    dropins: dict[str, list[Path]] = {}
    for p in sorted(unit_dir.iterdir()):
        stem, _, ext = p.name.rpartition(".")
        if ext in UNIT_KINDS and stem and (p.is_file() or p.is_symlink()):
            families.setdefault(stem, {})[ext] = p
        elif p.name.endswith(".d") and p.is_dir():
            base = p.name[:-2]
            stem, _, ext = base.rpartition(".")
            if ext not in UNIT_KINDS and base in UNIT_KINDS:
                stem, ext = f"(every {base})", base
            if ext not in UNIT_KINDS:
                continue
            confs = sorted(c for c in p.iterdir() if c.name.endswith(".conf"))
            if confs:
                dropins.setdefault(stem, []).extend(confs)
    return families, dropins


def systemctl_is_enabled(unit: str) -> str:
    """`systemctl --user is-enabled UNIT`, read-only; its exit code is not the answer, its first output line is."""
    done = subprocess.run(["systemctl", "--user", "is-enabled", unit], capture_output=True, text=True, check=False)
    lines = (done.stdout or "").strip().splitlines()
    return lines[0] if lines else "unknown"


def build(unit_dir: Path, is_enabled: Callable[[str], str] = systemctl_is_enabled) -> dict:
    """The manifest as data, sorted by unit name; no timestamp, so an unchanged machine gives the same bytes.

    Implements: machine-manifest/output-is-stable
    """
    git = Git()
    families, dropins = scan(unit_dir)
    units = []
    for name in sorted(set(families) | set(dropins)):
        family = families.get(name, {})
        entry = {"name": name, **describe(family, dropins.get(name, []), git, unit_dir)}
        main = next((f"{name}.{k}" for k in ("timer", "path", "socket", "service", "slice") if k in family), None)
        entry["enabled"] = is_enabled(main) if main and not name.startswith("(") else "n/a"
        units.append(entry)
    return {"generated_by": "aes scripts/machine_manifest.py build", "unit_dir": _short(str(unit_dir)),
            "units": units}


def dump(manifest: dict) -> str:
    return yaml.safe_dump(manifest, sort_keys=False, default_flow_style=False, width=1000)


def files_of(manifest: dict) -> dict[str, dict]:
    """Every unit and drop-in file in a manifest, by file name, with its source."""
    out: dict[str, dict] = {}
    for unit in manifest.get("units", []):
        for kind in UNIT_KINDS:
            item = unit.get(kind)
            if isinstance(item, dict) and item.get("file"):
                out[item["file"]] = item.get("source", {})
        for d in unit.get("dropins", []):
            out[d["file"]] = d.get("source", {})
    return out


def findings(current: dict, recorded: dict | None, copied: set[str] | frozenset[str] = frozenset()) -> dict[str, list[str]]:
    """What a clean machine would lose, and how the manifest differs from the disk.

    `copied` holds the paths whose units-repository copy matches the disk (`compare_units` same and link-same):
    a local-only file or a symlink outside git listed there is reported under `copied`, which does not fail.

    Implements: machine-manifest/local-only-units-are-reported
    Implements: machine-manifest/missing-or-untracked-target-is-reported
    Implements: machine-manifest/identical-copies-do-not-fail
    """
    now = files_of(current)
    result: dict[str, list[str]] = {"local-only": [], "bad-target": [], "gone-from-disk": [], "not-in-manifest": [],
                                    "copied": []}
    for name, src in sorted(now.items()):
        kind = src.get("kind")
        if kind in ("local-only", "symlink-outside-git") and name in copied:
            result["copied"].append(name)
        elif kind == "local-only":
            result["local-only"].append(name)
        elif kind == "symlink-missing-target":
            result["bad-target"].append(f"{name} (target missing)")
        elif kind == "symlink-outside-git":
            result["bad-target"].append(f"{name} (target not in a git repository)")
        elif kind == "git" and not src.get("tracked"):
            result["bad-target"].append(f"{name} (target not tracked by git)")
        elif kind == "git" and not src.get("committed"):
            result["bad-target"].append(f"{name} (target has uncommitted changes)")
    if recorded is not None:
        before = files_of(recorded)
        result["gone-from-disk"] = sorted(set(before) - set(now))
        result["not-in-manifest"] = sorted(set(now) - set(before))
    return result


LABELS = {"local-only": "(a) local-only files, lost on a clean machine",
          "bad-target": "(b) symlinks whose target is missing, outside git, untracked or uncommitted",
          "gone-from-disk": "(c) in the manifest, no longer on disk",
          "not-in-manifest": "(d) on disk, not in the manifest",
          "copied": "(e) local-only files and links with an identical copy in the units repository (not a failure)"}
FAILING = ("local-only", "bad-target", "gone-from-disk", "not-in-manifest")


SYMLINK_SUFFIX = ".symlink"
DEFAULT_UNITS_REPO = Path.home() / "code2/aes-config/machine-units"
DEFAULT_BACKUP_ROOT = Path.home() / "archive/systemd-units-replaced"


def repo_copies(units_repo: Path) -> tuple[dict[str, Path], dict[str, str]]:
    """Repository copies by unit-folder-relative path, and recorded symlinks (`NAME.symlink` holds the link target)."""
    files: dict[str, Path] = {}
    links: dict[str, str] = {}
    for p in sorted(units_repo.rglob("*")):
        if not p.is_file():
            continue
        rel = p.relative_to(units_repo).as_posix()
        if rel.endswith(SYMLINK_SUFFIX):
            links[rel[: -len(SYMLINK_SUFFIX)]] = p.read_text().strip()
        else:
            files[rel] = p
    return files, links


def _through_link(unit_dir: Path, rel: str) -> bool:
    """True when the destination file, or a folder between it and the unit folder, is a symlink."""
    path = unit_dir / rel
    return any(q.is_symlink() for q in [path, *path.parents] if q != unit_dir and unit_dir in q.parents)


def compare_units(unit_dir: Path, units_repo: Path) -> dict[str, list[str]]:
    """Disk against repository copies: same, differ, missing, and `linked` (disk path is a symlink or under one).

    Implements: machine-manifest/repository-copies-can-be-compared
    """
    files, links = repo_copies(units_repo)
    out: dict[str, list[str]] = {"same": [], "differ": [], "missing": [], "linked": [], "link-same": [], "link-differ": []}
    for rel, src in files.items():
        dest = unit_dir / rel
        if _through_link(unit_dir, rel):
            out["linked"].append(rel)
        elif not dest.exists():
            out["missing"].append(rel)
        elif dest.read_bytes() == src.read_bytes():
            out["same"].append(rel)
        else:
            out["differ"].append(rel)
    for rel, target in links.items():
        dest = unit_dir / rel
        out["link-same" if dest.is_symlink() and os.readlink(dest) == target else "link-differ"].append(rel)
    return out


def install_units(unit_dir: Path, units_repo: Path, apply: bool, backup_root: Path = DEFAULT_BACKUP_ROOT,
                  today: str | None = None) -> dict[str, list[str]]:
    """Copy repository copies that are missing or differ; back up a differing disk file first; never delete.

    A destination that is a symlink, or sits under one, is skipped and reported, never written through.
    Implements: machine-manifest/install-never-deletes-or-writes-through-links
    """
    today = today or datetime.date.today().isoformat()
    files, _ = repo_copies(units_repo)
    found = compare_units(unit_dir, units_repo)
    done: dict[str, list[str]] = {"installed": [], "replaced": [], "skipped-link": list(found["linked"])}
    for rel in found["missing"] + found["differ"]:
        dest = unit_dir / rel
        replaced = rel in found["differ"]
        if apply:
            if replaced:
                backup = backup_root / f"{rel.replace('/', '__')}-{today}"
                backup.mkdir(parents=True, exist_ok=True)
                shutil.copy2(dest, backup / dest.name)
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(files[rel], dest)
        done["replaced" if replaced else "installed"].append(rel)
    return done


def main(argv: list[str] | None = None, is_enabled: Callable[[str], str] = systemctl_is_enabled) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["build", "check", "check-units", "install-units"])
    ap.add_argument("--unit-dir", type=Path, default=Path.home() / ".config/systemd/user")
    ap.add_argument("--out", type=Path)
    ap.add_argument("--manifest", type=Path, default=Path.home() / "code2/aes-config/machine-layer.yaml")
    ap.add_argument("--units-repo", type=Path, default=DEFAULT_UNITS_REPO)
    ap.add_argument("--apply", action="store_true", help="install-units: really copy (the default is a dry run)")
    ap.add_argument("--dry-run", action="store_true", help="install-units: print what would change (the default)")
    ap.add_argument("--daemon-reload", action="store_true", help="install-units --apply: then run systemctl --user daemon-reload")
    ap.add_argument("--backup-root", type=Path, default=DEFAULT_BACKUP_ROOT)
    a = ap.parse_args(argv)
    if a.command == "check-units":
        found = compare_units(a.unit_dir, a.units_repo)
        print(f"machine_manifest: units in {a.units_repo} against {a.unit_dir}: same {len(found['same'])}, "
              f"differ {len(found['differ'])}, missing {len(found['missing'])}, under-a-symlink {len(found['linked'])}; "
              f"recorded symlinks same {len(found['link-same'])}, differ {len(found['link-differ'])}")
        for key in ("differ", "missing", "linked", "link-differ"):
            for name in found[key]:
                print(f"  {key}: {name}")
        return 1 if found["differ"] or found["link-differ"] else 0
    if a.command == "install-units":
        real = a.apply and not a.dry_run
        done = install_units(a.unit_dir, a.units_repo, real, a.backup_root)
        print(f"machine_manifest: install-units {'applied' if real else 'dry run, nothing written'}: "
              f"{len(done['installed'])} new, {len(done['replaced'])} replaced (backed up first), "
              f"{len(done['skipped-link'])} skipped (symlink)")
        for key, names in done.items():
            for name in names:
                print(f"  {key}: {name}")
        if real and a.daemon_reload:
            return subprocess.run(["systemctl", "--user", "daemon-reload"], check=False).returncode
        return 0
    current = build(a.unit_dir, is_enabled)
    if a.command == "build":
        text = dump(current)
        if a.out:
            a.out.write_text(text)
            print(f"machine_manifest: wrote {len(current['units'])} units, {len(files_of(current))} files to {a.out}")
        else:
            sys.stdout.write(text)
        return 0
    recorded = yaml.safe_load(a.manifest.read_text()) if a.manifest.exists() else None
    if recorded is None:
        print(f"machine_manifest: no manifest at {a.manifest}; (c) and (d) not checked")
    copied: set[str] = set()
    if a.units_repo.is_dir():
        same = compare_units(a.unit_dir, a.units_repo)
        copied = set(same["same"]) | set(same["link-same"])
    else:
        print(f"machine_manifest: no units repository at {a.units_repo}; no file counts as copied")
    found = findings(current, recorded, copied)
    print(f"machine_manifest: {len(current['units'])} units, {len(files_of(current))} files in {a.unit_dir}")
    for key, label in LABELS.items():
        print(f"{label}: {len(found[key])}")
        for name in found[key]:
            print(f"  {name}")
    return 1 if any(found[key] for key in FAILING) or recorded is None else 0


if __name__ == "__main__":
    sys.exit(main())
