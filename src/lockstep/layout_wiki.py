from __future__ import annotations

import re
from pathlib import Path

from lockstep.checks.spec import read_plan
from lockstep.checks.status import CHANGED, Report, Row, report
from lockstep.layout_plan import _data, has_layout
from lockstep.wiki_reach import reach_problems

WIKI_DIR = Path("generated/wiki")
MARKER = "<!-- generated by `lockstep check project`; do not edit -->"
_PURPOSE = re.compile(r"^## Purpose[ \t]*\n+(.+?)(?:\n\s*\n|\Z)", re.MULTILINE | re.DOTALL)


def enabled(root: Path) -> bool:
    """Say whether the repository asks for a generated wiki: a layout plan and `generated_wiki: true` in lockstep.yaml.

    Args:
        root: Repository root.

    Returns:
        True when both hold.
    """
    return has_layout(root) and _data(root).get("generated_wiki") is True


def _link(where: str) -> str:
    """A `file:line` as a Markdown link, relative to a page in generated/wiki/ so it is the same in every checkout."""
    path, _, number = where.rpartition(":")
    if not number.isdigit():
        return f"[`{where}`](../../{where})"
    return f"[`{where}`](../../{path}#L{number})"


def _label(requirement: Row, scenarios: list[Row]) -> str:
    """The coverage state of a requirement in words; pass or fail is left to `lockstep status`."""
    if not requirement.links:
        return "unimplemented"
    if requirement.state == CHANGED:
        return CHANGED
    if not scenarios:
        return "implemented, no scenarios"
    if any(not s.links for s in scenarios):
        return "implemented, a scenario has no test"
    return "implemented and tested"


def _summary(root: Path, capability: str, rows: list[str], coverage: Report) -> str:
    """One line saying what a capability is: its spec's Purpose when it has one, else its requirement count."""
    spec = root / coverage.requirements[rows[0]].where
    found = _PURPOSE.search(spec.read_text(encoding="utf-8")) if spec.is_file() else None
    purpose = " ".join(found.group(1).split()) if found else ""
    if purpose and not purpose.upper().startswith("TBD") and not purpose.startswith("Starter capability"):
        first = re.split(r"(?<=[.!?])\s", purpose)[0]
        return first if len(first) <= 200 else first[:197].rstrip() + "..."
    return f"{len(rows)} requirement(s), none described yet"


def _capability_page(capability: str, ids: list[str], coverage: Report, text: dict[str, str]) -> str:
    """One capability's page: each requirement with its text, status, implementing code, and scenarios with their tests."""
    lines = [f"# {capability}", "", MARKER, "",
             f"[All capabilities](index.md) — the wiki index. Spec: `{coverage.requirements[ids[0]].where}`. "
             "Pass or fail is not shown here (it changes with each run); `lockstep status` gives it.", ""]
    for ident in ids:
        row = coverage.requirements[ident]
        scenarios = [(i, s) for i, s in coverage.scenarios.items() if s.requirement == ident]
        lines += [f"## {ident.split('/', 1)[1].replace('-', ' ')}", "", f"ID: `{ident}`", "",
                  f"Status: **{_label(row, [s for _, s in scenarios])}**", "", text.get(ident, "").strip(), ""]
        lines += ["Implemented by:" if row.links else "Implemented by: nothing yet", ""]
        lines += [f"- `{symbol}` — {_link(where)}" for symbol, where in zip(row.links, row.files)]
        lines += [""] if row.links else []
        for sid, scenario in scenarios:
            tests = ", ".join(f"`{t}` ({_link(w)})" for t, w in zip(scenario.links, scenario.files))
            lines.append(f"- Scenario `{sid.split('/', 1)[1]}`: " + (f"tested by {tests}" if tests else "no test"))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _pages(root: Path, coverage: Report) -> dict[str, str]:
    """Every page, keyed by its name inside generated/wiki/: the index, then one per capability."""
    plan, pending = read_plan(root), read_plan(root, changes=True)
    text = {**plan.text, **pending.text}
    by_capability: dict[str, list[str]] = {}
    for ident in sorted(coverage.requirements):
        by_capability.setdefault(ident.split("/", 1)[0], []).append(ident)
    index = ["# Generated wiki", "", MARKER, "",
             "One page per OpenSpec capability: each requirement's text, the code that implements it, its tagged "
             "tests and its coverage state. Edit the specs, the code or the tests, not these pages.", ""]
    out: dict[str, str] = {}
    for capability, ids in by_capability.items():
        index.append(f"- [{capability}]({capability}.md) — {_summary(root, capability, ids, coverage)}")
        out[f"{capability}.md"] = _capability_page(capability, ids, coverage, text)
    out["index.md"] = "\n".join(index) + "\n"
    return out


def wiki_contents(root: Path, coverage: Report) -> dict[Path, str]:
    """The pages `lockstep check project` writes, by path; empty when the repository has not asked for a wiki.

    Args:
        root: Repository root.
        coverage: The coverage-only status report (no test results, so the pages do not depend on who ran them).

    Returns:
        Absolute path to page text.
    """
    if not enabled(root):
        return {}
    return {root / WIKI_DIR / name: body for name, body in _pages(root, coverage).items()}


def wiki_problems(root: Path, coverage: Report) -> list[str]:
    """Each way the generated pages break the wiki rule: a page more than two links from the index, a link with no summary.

    Args:
        root: Repository root.
        coverage: The coverage-only status report.

    Returns:
        Plain-words problems; empty when the wiki is not enabled or is sound.
    """
    return reach_problems(_pages(root, coverage)) if enabled(root) else []


def orphan_pages(root: Path, keep: set[Path]) -> list[Path]:
    """The pages this generator wrote earlier that it would not write now (their capability is gone).

    Args:
        root: Repository root.
        keep: The paths `wiki_contents` returned.

    Returns:
        Existing `generated/wiki/*.md` files carrying the generator's marker that are not in `keep`.
    """
    if not enabled(root):
        return []
    return [p for p in sorted((root / WIKI_DIR).glob("*.md")) if p not in keep and MARKER in p.read_text(encoding="utf-8")]


def print_wiki(root: Path) -> int:
    """Print every page as plain text (what `python -m lockstep.wiki` shows in a layout repository).

    Args:
        root: Repository root.

    Returns:
        0.
    """
    for name, body in _pages(root, report(root, use_results=False)).items():
        print(f"===== generated/wiki/{name}\n{body}")
    return 0
